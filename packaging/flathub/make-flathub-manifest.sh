#!/bin/sh
# make-flathub-manifest.sh <tag>: Flathub variant of the manifest - the local "dir" source of the
# ksipphone module is replaced by the git tag and its commit (Flathub needs reproducible sources).
set -e
TAG="$1"; ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
COMMIT=$(git -C "$ROOT" rev-list -n 1 "$TAG")
OUT="$ROOT/packaging/flathub/io.github.gongsearch.KSipPhone.yml"
python3 - "$ROOT/packaging/flatpak/io.github.gongsearch.KSipPhone.yml" "$OUT" "$TAG" "$COMMIT" <<'PY'
import sys
src, out, tag, commit = sys.argv[1:]
s = open(src).read()
old = "      - type: dir\n        path: ../.."
assert s.count(old) == 1
s = s.replace(old, "      - type: git\n        url: https://github.com/gongsearch/ksipphone.git\n        tag: %s\n        commit: %s" % (tag, commit))
s = s.replace("# Local build:", "# Flathub manifest (generated by packaging/flathub/make-flathub-manifest.sh). Local build of the dev tree:")
open(out, "w").write(s)
PY
echo "wrote $OUT ($TAG = $COMMIT)"
